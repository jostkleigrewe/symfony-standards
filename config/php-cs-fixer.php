<?php

declare(strict_types=1);

/*
 * DE: Gemeinsame php-cs-fixer-Konfiguration: PER Coding Style 3.0 plus strict_types und sortierte Imports.
 *     Aufruf aus der .php-cs-fixer.dist.php des Projekts:
 *     return (require __DIR__.'/vendor/jostkleigrewe/symfony-standards/config/php-cs-fixer.php')(__DIR__);
 * EN: Shared php-cs-fixer config (PER-CS 3.0 + strict_types + ordered imports), called with the project root.
 */

use PhpCsFixer\Config;
use PhpCsFixer\Finder;

return static function (string $projectDir, array $extraRules = []): Config {
    $finder = (new Finder())
        ->in($projectDir)
        ->exclude(['var', 'vendor', 'node_modules', 'public/assets', 'assets/vendor'])
        // DE: Von Symfony Flex/Kernel generiert — Flex schreibt sie neu und würde Fixes wieder entfernen.
        // EN: Generated by Flex/the kernel; fixes would be overwritten.
        ->notPath(['config/bundles.php', 'config/reference.php']);

    return (new Config())
        ->setRiskyAllowed(true)
        ->setCacheFile(sprintf('%s/php-cs-fixer-%s.cache', sys_get_temp_dir(), md5($projectDir)))
        ->setRules(array_merge([
            '@PER-CS3x0' => true,
            'declare_strict_types' => true,
            'no_unused_imports' => true,
            'ordered_imports' => ['sort_algorithm' => 'alpha', 'imports_order' => ['class', 'function', 'const']],
        ], $extraRules))
        ->setFinder($finder);
};
